    SAFE_CAST(atl AS NUMERIC) AS atl_usd,
    SAFE_CAST(atl_change_percentage AS FLOAT64) AS atl_change_percentage,
    atl_date,
    SAFE_CAST(roi_percentage AS FLOAT64) AS roi_percentage,
    last_updated,
    extracted_at
