    coin_id,
    symbol,
    name,
    image_url,
    SAFE_CAST(current_price AS NUMERIC) AS current_price_usd,
    SAFE_CAST(market_cap AS NUMERIC) AS market_cap_usd,
    SAFE_CAST(market_cap_rank AS INT64) AS market_cap_rank,
    SAFE_CAST(fully_diluted_valuation AS NUMERIC) AS fully_diluted_valuation_usd,
    SAFE_CAST(total_volume AS NUMERIC) AS total_volume_24h_usd,
